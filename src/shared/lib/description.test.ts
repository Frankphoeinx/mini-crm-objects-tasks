import { describe, expect, it } from 'vitest';
import { plainText } from './description';

const PATH = '11111111-1111-1111-1111-111111111111/22222222-2222-2222-2222-222222222222.png';

describe('plainText', () => {
  it.each([
    ['простой текст без изменений', 'Бетон М300, 3,5 на 4 метра', 'Бетон М300, 3,5 на 4 метра'],
    ['пустое описание', '', ''],
    ['перенос строки редактора', 'Первое  \nВторое', 'Первое\nВторое'],
    ['старый перенос строки', 'Первое\nВторое', 'Первое\nВторое'],
    ['жирный и курсив', '**важно** и *срочно*', 'важно и срочно'],
    ['вложенное оформление', '**очень *важно***', 'очень важно'],
    ['курсив через подчёркивание', '_срочно_ и snake_case_name', 'срочно и snake_case_name'],
    ['заголовок', '## Этап 1', 'Этап 1'],
    ['маркированный список', '- кирпич\n- цемент', 'кирпич\nцемент'],
    ['нумерованный список оставляет номера', '1. кирпич\n2. цемент', '1. кирпич\n2. цемент'],
    ['картинка словом', `Смотри ![](${PATH}) тут`, 'Смотри [картинка] тут'],
    ['чужая картинка словом', '![схема](https://evil.example/x.png)', '[картинка]'],
    ['экранированные звёздочки остаются', 'Плита 3\\*5\\*2 и \\*важно\\*', 'Плита 3*5*2 и *важно*'],
    ['звёздочки между цифрами не разметка', 'Плита 3*5*2 м', 'Плита 3*5*2 м'],
    ['звёздочки с пробелами не разметка', '2 * 3 * 4', '2 * 3 * 4'],
    ['HTML из редактора показан текстом', '&lt;img src=x onerror=alert(1)&gt;', '<img src=x onerror=alert(1)>'],
    ['написанный амперсанд с названием не раскрывается дважды', '&amp;lt;', '&lt;'],
    ['пустая строка редактора', 'А\n\n&nbsp;\n\nБ', 'А\n\n\n\nБ'],
  ])('%s', (_name, markdown, text) => {
    expect(plainText(markdown)).toBe(text);
  });
});
